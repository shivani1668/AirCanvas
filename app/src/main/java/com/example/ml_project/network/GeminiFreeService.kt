package com.example.ml_project.network

import android.graphics.Bitmap
import com.example.ml_project.model.SolvedEquation
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.io.ByteArrayOutputStream
import java.util.concurrent.TimeUnit
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/**
 * Service for sending drawn mathematical images to Google Gemini 1.5/2.0 Flash Free Tier API.
 */
object GeminiFreeService {

    private val client = OkHttpClient.Builder()
        .connectTimeout(30, TimeUnit.SECONDS)
        .readTimeout(30, TimeUnit.SECONDS)
        .writeTimeout(30, TimeUnit.SECONDS)
        .build()

    suspend fun solveMathImage(
        bitmap: Bitmap,
        apiKey: String
    ): SolvedEquation = withContext(Dispatchers.IO) {
        if (apiKey.isBlank()) {
            throw IllegalArgumentException("Gemini API Key is empty. Please configure your free API Key in settings or use Offline Engine.")
        }

        val base64Image = bitmapToBase64(bitmap)

        val promptText = """
            You are an expert AI mathematician. Analyze this hand-drawn mathematical equation or drawing.
            1. Extract the exact handwritten expression or equation.
            2. Categorize the problem (e.g. Arithmetic, Linear Algebra, Quadratic Equation, Calculus, Trigonometry).
            3. Provide a clear step-by-step breakdown explaining how to solve it.
            4. Provide the final simplified answer.

            Return strictly a JSON object with this exact structure (no extra markdown formatting, plain JSON):
            {
              "expression": "2x + 5 = 15",
              "category": "Algebra",
              "steps": [
                "Step 1: Subtract 5 from both sides: 2x = 10",
                "Step 2: Divide by 2: x = 5"
              ],
              "finalAnswer": "x = 5"
            }
        """.trimIndent()

        val requestJson = JSONObject().apply {
            val contents = JSONArray().apply {
                val contentObj = JSONObject().apply {
                    val parts = JSONArray().apply {
                        put(JSONObject().apply {
                            put("text", promptText)
                        })
                        put(JSONObject().apply {
                            put("inline_data", JSONObject().apply {
                                put("mime_type", "image/jpeg")
                                put("data", base64Image)
                            })
                        })
                    }
                    put("parts", parts)
                }
                put(contentObj)
            }
            put("contents", contents)
        }

        val url = "https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=$apiKey"
        val requestBody = requestJson.toString().toRequestBody("application/json; charset=utf-8".toMediaType())

        val request = Request.Builder()
            .url(url)
            .post(requestBody)
            .build()

        val response = client.newCall(request).execute()
        val responseBody = response.body?.string() ?: throw Exception("Empty response from Gemini API")

        if (!response.isSuccessful) {
            val errorMsg = try {
                JSONObject(responseBody).getJSONObject("error").getString("message")
            } catch (e: Exception) {
                "API Error ${response.code}: $responseBody"
            }
            throw Exception(errorMsg)
        }

        parseGeminiResponse(responseBody)
    }

    private fun parseGeminiResponse(jsonString: String): SolvedEquation {
        val root = JSONObject(jsonString)
        val candidates = root.optJSONArray("candidates")
            ?: throw Exception("Invalid response structure from Gemini API")

        if (candidates.length() == 0) {
            throw Exception("No solution generated by Gemini AI")
        }

        val content = candidates.getJSONObject(0).getJSONObject("content")
        val parts = content.getJSONArray("parts")
        val rawText = parts.getJSONObject(0).getString("text").trim()

        // Clean json blocks ```json ... ```
        val cleanJson = rawText
            .removePrefix("```json")
            .removePrefix("```")
            .removeSuffix("```")
            .trim()

        val json = JSONObject(cleanJson)
        val expression = json.optString("expression", "Handwritten Expression")
        val category = json.optString("category", "General Math")
        val stepsArray = json.optJSONArray("steps")
        val steps = mutableListOf<String>()
        if (stepsArray != null) {
            for (i in 0 until stepsArray.length()) {
                steps.add(stepsArray.getString(i))
            }
        }
        val finalAnswer = json.optString("finalAnswer", "Solved")

        return SolvedEquation(
            expression = expression,
            category = category,
            solutionSteps = if (steps.isEmpty()) listOf("Recognized: $expression", "Calculated by Gemini AI") else steps,
            finalAnswer = finalAnswer,
            source = "Google Gemini AI (Free)"
        )
    }

    private fun bitmapToBase64(bitmap: Bitmap): String {
        val outputStream = ByteArrayOutputStream()
        bitmap.compress(Bitmap.CompressFormat.JPEG, 90, outputStream)
        val byteArray = outputStream.toByteArray()
        return android.util.Base64.encodeToString(byteArray, android.util.Base64.NO_WRAP)
    }
}
